"""Generate axbrief-data.js from news_data.json (JSON source of truth).

news_data.json is section-keyed:
  { "sections": { "design": {today, days}, "music": {...}, ... } }

Emits:
  window.AX_SECTIONS = { "<section>": { "news": [...today cards...], "days": [...deck...] }, ... }
  window.AX_NEWS / window.AX_DAYS = the `design` section (back-compat for the
  large-card app until it becomes section-aware).
"""
import argparse, html, json, os, shutil, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from i18n_text import LANGS, flatten

HEADER = ("/* AUTO-GENERATED by pipeline/build_data.py — do not hand-edit.\n"
          "   Source of truth: pipeline/news_data.json */\n")

DEFAULT_BASE_URL = "https://axitnow.com"

# Section display order + labels for the UI tabs.
SECTION_ORDER = ["design", "music", "movies", "games", "books", "gadgets", "science",
                 "politics"]
SECTION_LABELS = {"design": "Design", "music": "Music", "movies": "Movies",
                  "games": "Games", "books": "Books", "gadgets": "Gadgets",
                  "science": "Science", "politics": "Politics"}

class DuplicateCardError(ValueError):
    pass

def assert_no_duplicates(section, today, days):
    """Within ONE section: no two cards (today + every deck day) may share a URL —
    hard build failure. A shared thumbnail is allowed but warned (distinct articles
    may reuse a source's site-wide OG image)."""
    cards = [("today", c) for c in today.get("cards", [])]
    for day in days:
        cards += [(day["date"], c) for c in day["cards"]]
    seen_url, seen_img, dups = {}, {}, []
    for where, c in cards:
        u, img = c.get("url"), c.get("image")
        if u in seen_url:
            dups.append(f"[{section}] duplicate URL {u!r}: {seen_url[u]} & {where}")
        else:
            seen_url[u] = where
        if img:
            if img in seen_img:
                print(f"WARN: [{section}] shared thumbnail {img!r}: {seen_img[img]} & {where} "
                      f"(distinct articles — consider a per-article image)", file=sys.stderr)
            else:
                seen_img[img] = where
    if dups:
        raise DuplicateCardError("; ".join(dups))

def split_teaser(data):
    """Teaser paywall split — v2 (revises the v1 "first-paragraph teaser + removed
    locked cards" model after live user feedback: the free card's deep-dive should
    be fully readable, and locked cards should render as real cards, blurred, not
    disappear).

    Per section:
      - today.cards[0] (the "free card") stays public with its COMPLETE original
        `full` (all blocks) — no truncation, no fade, no CTA. `free: True` is set,
        and `hasFull` reflects whether the card had any deep-dive blocks at all.
      - today.cards[1:] ("locked cards") STAY in the public payload — front fields
        (id, eyebrow, headline, body, tool, source, url, accent, motif, image) are
        untouched — but `full` is stripped out and stashed in `premium` for a
        future unlock. `locked: True` is set, and `hasFull` reflects whether the
        card had any deep-dive blocks (so the UI knows a locked card "has more"
        even though it can't render it).
      - `today["lockedCount"]` still records how many today cards are locked.
      - Archive (`days`) cards are gated like locked today-cards (v3: the Past
        Days archive is now Pro-only). For every archive card: `full` is
        stripped out and stashed in `premium` (same map, keyed
        "<section>/<id>"), `locked: True` is set, and `hasFull` reflects
        whether the card had any deep-dive blocks at all. Front fields stay
        public (visible blurred, same policy as locked today cards).

    Mutates `data` in place. Returns premium:
      premium { "<section>/<id>": {"blocks": <ORIGINAL full blocks>} }
              — locked (today.cards[1:]) cards' AND all archive cards' stashed
                deep-dive blocks. Free cards need no stash: their full content
                is already public. IDs are unique per section; if an archive
                card and a locked today-card ever shared an id, the later
                entry wins (acceptable — ids are unique per section).
    """
    sections = data.get("sections")
    if sections is None:
        sections = {"design": {"today": data.get("today", {"cards": []}),
                               "days": data.get("days", [])}}
    premium = {}

    def blocks_of(c):
        return ((c.get("full") or {}).get("blocks")) or []

    for sec, s in sections.items():
        today = s.get("today") or {"cards": []}
        cards = list(today.get("cards", []))
        today["lockedCount"] = max(0, len(cards) - 1)
        if cards:
            free = cards[0]
            free["free"] = True
            free["hasFull"] = len(blocks_of(free)) > 0
            # free["full"] stays exactly as-is: the complete, untruncated deep-dive.
            for c in cards[1:]:
                blocks = blocks_of(c)
                cid = c.get("id")
                if cid and blocks:
                    premium["%s/%s" % (sec, cid)] = {"blocks": blocks}
                c["hasFull"] = len(blocks) > 0
                c["locked"] = True
                c.pop("full", None)   # strip the deep-dive out of the public card
            today["cards"] = cards
        else:
            today["cards"] = []
        # archive cards: gated like locked today-cards — full stripped + stashed,
        # locked: True set, front fields stay public.
        for day in s.get("days", []):
            for c in day.get("cards", []):
                blocks = blocks_of(c)
                cid = c.get("id")
                if cid and blocks:
                    premium["%s/%s" % (sec, cid)] = {"blocks": blocks}
                c["hasFull"] = len(blocks) > 0
                c["locked"] = True
                c.pop("full", None)
    return premium

def to_js(data):
    # Back-compat: accept an old non-sectioned file too.
    sections = data.get("sections")
    if sections is None:
        sections = {"design": {"today": data.get("today", {"cards": []}), "days": data.get("days", [])}}

    ax_sections = {}
    for sec in SECTION_ORDER:
        s = sections.get(sec) or {"today": {"cards": []}, "days": []}
        today = s.get("today") or {"cards": []}
        days = s.get("days", [])
        assert_no_duplicates(sec, today, days)
        # Only surface a section once it has content — keeps a newly-added section
        # (e.g. science) from rendering an empty tab before its first run. `design`
        # is always emitted for the AX_NEWS/AX_DAYS back-compat globals below.
        if sec != "design" and not today.get("cards") and not days:
            continue
        ax_sections[sec] = {"label": SECTION_LABELS.get(sec, sec.title()),
                            "news": today.get("cards", []), "days": days,
                            "lockedCount": today.get("lockedCount", 0)}

    design = ax_sections.get("design", {"news": [], "days": []})

    def dump(obj):
        return json.dumps(obj, ensure_ascii=False, indent=2)
    return (HEADER +
            "(function () {\n" +
            "  window.AX_SECTIONS = " + dump(ax_sections) + ";\n" +
            "  window.AX_SECTION_ORDER = " + dump(SECTION_ORDER) + ";\n" +
            "  // back-compat (large-card app reads these until it becomes section-aware):\n" +
            "  window.AX_NEWS = " + dump(design["news"]) + ";\n" +
            "  window.AX_DAYS = " + dump(design["days"]) + ";\n" +
            "})();\n")

SHARE_TMPL = """<!DOCTYPE html>
<html lang="{lang}">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>{title} · AX-it NOW</title>
<meta name="description" content="{desc}">
<meta property="og:type" content="article">
<meta property="og:site_name" content="AX-it NOW">
<meta property="og:locale" content="{locale}">
<meta property="og:title" content="{title}">
<meta property="og:description" content="{desc}">
<meta property="og:url" content="{ogurl}">{img_tags}
<meta name="twitter:card" content="{tw_card}">
<meta name="twitter:title" content="{title}">
<meta name="twitter:description" content="{desc}">{tw_img}
<link rel="canonical" href="{appurl}">
<meta http-equiv="refresh" content="0; url={appurl}">
<script>location.replace({appurl_js})</script>
</head>
<body style="margin:0;height:100vh;display:flex;align-items:center;justify-content:center;background:#f1ece4;font-family:Pretendard,system-ui,sans-serif;color:#171717">
<a href="{appurl}" style="color:#171717;text-decoration:none;font-size:15px">{open_label}</a>
</body>
</html>
"""

LOCALES = {"en": "en_US", "ko": "ko_KR", "ja": "ja_JP", "zh": "zh_CN", "es": "es_ES"}
OPEN_LABEL = {"en": "AX-it NOW — open card →", "ko": "AX-it NOW — 카드 열기 →",
              "ja": "AX-it NOW — カードを開く →", "zh": "AX-it NOW — 打开卡片 →",
              "es": "AX-it NOW — abrir tarjeta →"}


def localize(data, lang):
    """Deep copy of news_data with every card flattened to `lang` (see i18n_text)."""
    out = json.loads(json.dumps(data))
    for s in (out.get("sections") or {}).values():
        today = s.get("today") or {}
        today["cards"] = [flatten(c, lang) for c in today.get("cards", [])]
        for day in s.get("days", []):
            day["cards"] = [flatten(c, lang) for c in day.get("cards", [])]
    return out


def merge_premium(path, premium):
    merged = {}
    if os.path.exists(path):
        try:
            old = json.load(open(path, encoding="utf-8"))
            merged = dict(old.get("cards", old) or {})
        except (json.JSONDecodeError, OSError):
            merged = {}
    merged.update(premium)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump({"cards": merged}, f, ensure_ascii=False, indent=2)


def emit_share_pages(sections, base_url, share_root, lang="ko", legacy=False):
    """Per-card static share pages with OG/Twitter meta (so pasted links unfurl with
    the card's image + headline) + a redirect into the app. `legacy` emits the
    original ko-only, unprefixed path (s/<section>/<id>.html, /?c=...) for back-compat;
    otherwise pages are language-prefixed (s/<lang>/<section>/<id>.html, /<lang>/?c=...).
    Callers are responsible for clearing <share_root>/s/ once before the first call."""
    base = base_url.rstrip("/")
    s_root = os.path.join(share_root, "s")
    n = 0
    for sec, payload in sections.items():
        cards = list(payload.get("news", []))
        for day in payload.get("days", []):
            cards += day.get("cards", [])
        seen = set()
        for c in cards:
            cid = c.get("id")
            if not cid or cid in seen:
                continue
            seen.add(cid)
            e = lambda s: html.escape(str(s or ""), quote=True)
            title = e((c.get("headline") or "").replace("\n", " ").strip())
            desc = e((c.get("body") or "").strip())
            if legacy:
                appurl = f"{base}/?c={sec}:{cid}"
                ogurl = f"{base}/s/{sec}/{cid}"
                d = os.path.join(s_root, sec)
            else:
                appurl = f"{base}/{lang}/?c={sec}:{cid}"
                ogurl = f"{base}/s/{lang}/{sec}/{cid}"
                d = os.path.join(s_root, lang, sec)
            img = c.get("image")
            if img:
                imgurl = e(f"{base}/{str(img).lstrip('/')}")
                img_tags = (f'\n<meta property="og:image" content="{imgurl}">'
                            f'\n<meta property="og:image:alt" content="{title}">')
                tw_img = f'\n<meta name="twitter:image" content="{imgurl}">'
                tw_card = "summary_large_image"
            else:
                img_tags, tw_img, tw_card = "", "", "summary"
            page = SHARE_TMPL.format(title=title, desc=desc, ogurl=e(ogurl),
                                     appurl=e(appurl), appurl_js=json.dumps(appurl),
                                     img_tags=img_tags, tw_img=tw_img, tw_card=tw_card,
                                     lang=lang, locale=LOCALES[lang], open_label=OPEN_LABEL[lang])
            os.makedirs(d, exist_ok=True)
            open(os.path.join(d, f"{cid}.html"), "w", encoding="utf-8").write(page)
            n += 1
    return n

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--in", dest="inp", default="news_data.json")
    ap.add_argument("--out", dest="out", default="../axbrief-data.js")
    ap.add_argument("--share-root", default=None,
                    help="if set, also emit per-card OG share pages under <root>/s/")
    ap.add_argument("--base-url", default=DEFAULT_BASE_URL,
                    help="absolute origin for OG urls/images in share pages")
    a = ap.parse_args()
    data = json.load(open(a.inp, encoding="utf-8"))
    out_dir = os.path.dirname(os.path.abspath(a.out))
    prem_dir = os.path.join(out_dir, "premium")
    if a.share_root:
        shutil.rmtree(os.path.join(a.share_root, "s"), ignore_errors=True)
    for lang in LANGS:
        ldata = localize(data, lang)
        premium = split_teaser(ldata)
        js = to_js(ldata)
        open(os.path.join(out_dir, f"axbrief-data.{lang}.js"), "w", encoding="utf-8").write(js)
        by_sec = {}
        for key, v in premium.items():
            by_sec.setdefault(key.split("/", 1)[0], {})[key] = v
        for sec, part in by_sec.items():
            merge_premium(os.path.join(prem_dir, lang, f"{sec}.json"), part)
        if lang == "ko":
            open(a.out, "w", encoding="utf-8").write(js)              # legacy path
            merge_premium(os.path.join(prem_dir, "full.json"), premium)  # legacy ko map
        if a.share_root:
            norm = {sec: {"news": (s.get("today") or {}).get("cards", []), "days": s.get("days", [])}
                    for sec, s in (ldata.get("sections") or {}).items()}
            n = emit_share_pages(norm, a.base_url, a.share_root, lang=lang)
            if lang == "ko":
                emit_share_pages(norm, a.base_url, a.share_root, lang="ko", legacy=True)
            print(f"share pages [{lang}]: {n}")

if __name__ == "__main__":
    main()
